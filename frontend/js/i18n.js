const translateDynamicString = (value) => {
  if (siteTranslations[value]) return siteTranslations[value];
  const priceMatch = value.match(/^(\d+) din$/);
  if (priceMatch) return `${priceMatch[1]} RSD`;
  const countMatch = value.match(/^(\d+) proizvoda?$/);
  if (countMatch) return `${countMatch[1]} ${countMatch[1] === "1" ? "item" : "items"}`;
  return value;
};

const applyTextNodeLanguage = (node) => {
  if (!originalTextNodes.has(node)) originalTextNodes.set(node, node.nodeValue);
  const original = originalTextNodes.get(node);
  const trimmed = original.trim();
  if (!trimmed) return;
  const translated = currentLanguage === "en" ? translateDynamicString(trimmed) : trimmed;
  node.nodeValue = original.replace(trimmed, translated);
};

const applyElementLanguage = (element) => {
  if (element.matches("script, style")) return;
  element.childNodes.forEach((node) => {
    if (node.nodeType === Node.TEXT_NODE) applyTextNodeLanguage(node);
  });

  let attributeMap = originalAttributes.get(element);
  if (!attributeMap) {
    attributeMap = {};
    originalAttributes.set(element, attributeMap);
  }
  translatableAttributes.forEach((attribute) => {
    if (!element.hasAttribute(attribute)) return;
    if (!(attribute in attributeMap)) attributeMap[attribute] = element.getAttribute(attribute);
    const original = attributeMap[attribute];
    element.setAttribute(attribute, currentLanguage === "en" ? translateDynamicString(original) : original);
  });
};

const applyLanguage = () => {
  isApplyingLanguage = true;
  document.documentElement.lang = currentLanguage === "en" ? "en" : "sr-Latn";
  const metadata = pageMetadata[originalDocumentTitle];
  document.title = currentLanguage === "en" && metadata ? metadata[0] : originalDocumentTitle;
  if (descriptionMeta) descriptionMeta.content = currentLanguage === "en" && metadata ? metadata[2] : originalDescription;
  document.querySelectorAll("body, body *").forEach(applyElementLanguage);
  document.querySelectorAll("[data-language]").forEach((button) => {
    const isActive = button.dataset.language === currentLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
  isApplyingLanguage = false;
};

const setLanguage = (language) => {
  currentLanguage = language === "en" ? "en" : "sr";
  localStorage.setItem("caffe-language", currentLanguage);
  applyLanguage();
  window.dispatchEvent(new CustomEvent("site-language-change", { detail: { language: currentLanguage } }));
};

const languageSwitcher = document.createElement("div");
languageSwitcher.className = "language-switcher";
languageSwitcher.setAttribute("aria-label", "Izbor jezika");
["sr", "en"].forEach((language) => {
  const button = document.createElement("button");
  button.type = "button";
  button.dataset.language = language;
  button.textContent = language.toUpperCase();
  button.setAttribute("aria-label", language === "sr" ? "Srpski jezik" : "English language");
  button.addEventListener("click", () => setLanguage(language));
  languageSwitcher.append(button);
});

const headerInner = document.querySelector(".site-header__inner");
const navigationToggle = headerInner?.querySelector("[data-nav-toggle]");
if (headerInner) headerInner.insertBefore(languageSwitcher, navigationToggle || null);

const translationObserver = new MutationObserver((mutations) => {
  if (isApplyingLanguage) return;
  mutations.forEach((mutation) => {
    mutation.addedNodes.forEach((node) => {
      if (node.nodeType === Node.TEXT_NODE) applyTextNodeLanguage(node);
      if (node.nodeType === Node.ELEMENT_NODE) {
        applyElementLanguage(node);
        node.querySelectorAll("*").forEach(applyElementLanguage);
      }
    });
  });
});

translationObserver.observe(document.body, { childList: true, subtree: true });
window.siteI18n = {
  getLanguage: () => currentLanguage,
  setLanguage,
  choose: (serbian, english) => currentLanguage === "en" ? english : serbian,
  translate: (value) => currentLanguage === "en" ? translateDynamicString(value) : value
};
